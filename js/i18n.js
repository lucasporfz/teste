let LANG = 'pt';
const t = key => (I18N[LANG] && I18N[LANG][key]) || key;

function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    el.textContent = t(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.placeholder = t(key);
  });
  document.documentElement.lang = LANG === 'pt' ? 'pt-BR' : 'en';
  document.title = t('title');
  document.getElementById('langPt').classList.toggle('active', LANG === 'pt');
  document.getElementById('langEn').classList.toggle('active', LANG === 'en');
  if (typeof updateUI === 'function') updateUI();
  if (typeof drawAll === 'function' && typeof cache !== 'undefined' && cache) drawAll();
  const st = document.getElementById('simStatus');
  if (st && typeof cache !== 'undefined' && cache && typeof N_SESSIONS !== 'undefined') {
    const totalHours = N_SESSIONS * SESSION_SECONDS / 3600 * N_LEVELS;
    const locale = LANG === 'pt' ? 'pt-BR' : 'en-US';
    st.textContent = t('status_done')
      .replace('{n}', N_SESSIONS)
      .replace('{h}', SESSION_SECONDS / 3600)
      .replace('{total}', totalHours.toLocaleString(locale))
      .replace('{elapsed}', lastElapsed || '—');
  }
  const modal = document.getElementById('guideModal');
  if (modal && modal.classList.contains('open')) {
    document.getElementById('guideContent').innerHTML = GUIDE[LANG];
  }
  // Re-renderizar cards do validador se modal estiver aberto e tiver dados
  const valModal = document.getElementById('validatorModal');
  if (valModal && valModal.classList.contains('open') && typeof lastValidatorData !== 'undefined' && lastValidatorData) {
    if (typeof renderValidatorExtracted === 'function') renderValidatorExtracted(lastValidatorData);
    if (typeof renderValidatorFunnel === 'function') renderValidatorFunnel(lastValidatorData);
    if (typeof renderValidatorHistogram === 'function') renderValidatorHistogram(lastValidatorData, lastSimHitsHist);
    if (typeof renderValidatorModelHelp === 'function') renderValidatorModelHelp(lastValidatorData);
  }
}

document.getElementById('langPt').addEventListener('click', () => { LANG = 'pt'; applyI18n(); });
document.getElementById('langEn').addEventListener('click', () => { LANG = 'en'; applyI18n(); });
